-- | File transfers with friends.
module Network.Tox.C.File
    ( toxFileById
    , toxFileSend
    , toxFileControl
    , toxFileSeek
    , toxFileGetFileId
    , toxFileSendChunk
    ) where

import           Data.ByteString       (ByteString)
import           Data.Word             (Word64)
import qualified FFI.Tox.Tox           as Raw
import           Foreign.C.Enum        (callErrFun, callErrFun_, toCEnum)
import           Network.Tox.C.Marshal (getFixedBytesErr, withBytesLen,
                                        withFixedBytes, withMaybeFixedBytes)
import           Network.Tox.C.Types   (ErrFileById, ErrFileControl, ErrFileGet,
                                        ErrFileSeek, ErrFileSend,
                                        ErrFileSendChunk, FileControl, FileId,
                                        FileKind (..), FileNumber (..),
                                        FriendNumber (..), Tox (..))

-- | Return the file number associated with the specified friend number and File
-- ID.
--
-- * @friendNumber@: The friend number of the friend the file is being sent to
--   or received from.
-- * @fileId@: A memory region of at least
--   'Network.Tox.C.Constants.toxFileIdLength' bytes.
toxFileById
    :: Tox -> FriendNumber -> FileId -> IO (Either ErrFileById FileNumber)
toxFileById (Tox tox) (FriendNumber friendNumber) fileId =
    withFixedBytes fileId $ \fileIdPtr ->
        fmap FileNumber
            <$> callErrFun (Raw.tox_file_by_id tox friendNumber fileIdPtr)

-- | Send a file transmission request.
--
-- Maximum filename length is 'Network.Tox.C.Constants.toxMaxFilenameLength'
-- bytes. The filename should generally just be a file name, not a path with
-- directory names.
--
-- If a non-UINT64_MAX file size is provided, it can be used by both sides to
-- determine the sending progress. File size can be set to UINT64_MAX for
-- streaming data of unknown size.
--
-- File transmission occurs in chunks, which are requested through the
-- @file_chunk_request@ event.
--
-- When a friend goes offline, all file transfers associated with the friend
-- get purged.
--
-- If the file contents change during a transfer, the behaviour is unspecified
-- in general. What will actually happen depends on the mode in which the file
-- was modified and how the client determines the file size.
--
-- \- If the file size was increased \- and sending mode was streaming
-- (file_size = UINT64_MAX), the behaviour will be as expected. \- and sending
-- mode was file (file_size != UINT64_MAX), the file_chunk_request callback
-- will receive length = 0 when Tox thinks the file transfer has finished. If
-- the client remembers the file size as it was when sending the request, it
-- will terminate the transfer normally. If the client re-reads the size, it
-- will think the friend cancelled the transfer. \- If the file size was
-- decreased \- and sending mode was streaming, the behaviour is as expected.
-- \- and sending mode was file, the callback will return 0 at the new
-- (earlier) end-of-file, signaling to the friend that the transfer was
-- cancelled. \- If the file contents were modified \- at a position before
-- the current read, the two files (local and remote) will differ after the
-- transfer terminates. \- at a position after the current read, the file
-- transfer will succeed as expected. \- In either case, both sides will
-- regard the transfer as complete and successful.
--
-- * @friendNumber@: The friend number of the friend the file send request
--   should be sent to.
-- * @kind@: The meaning of the file to be sent.
-- * @fileSize@: Size in bytes of the file the client wants to send,
--   UINT64_MAX if unknown or streaming.
-- * @fileId@: A file identifier of length
--   'Network.Tox.C.Constants.toxFileIdLength' that can be used to uniquely
--   identify file transfers across Tox restarts. If NULL, a random one will
--   be generated by the library. It can then be obtained by using
--   @tox_file_get_file_id()@.
-- * @filename@: Name of the file. Does not need to be the actual name. This
--   name will be sent along with the file send request.
toxFileSend
    :: Tox
    -> FriendNumber
    -> FileKind
    -> Word64
    -> Maybe FileId
    -> ByteString
    -> IO (Either ErrFileSend FileNumber)
toxFileSend (Tox tox) (FriendNumber friendNumber) (FileKind kind) fileSize
    fileId filename =
    withMaybeFixedBytes fileId $ \fileIdPtr ->
    withBytesLen filename $ \filenamePtr filenameLen ->
        fmap FileNumber
            <$> callErrFun
                (Raw.tox_file_send tox friendNumber kind fileSize fileIdPtr
                    filenamePtr filenameLen)

-- | Sends a file control command to a friend for a given file transfer.
--
-- * @friendNumber@: The friend number of the friend the file is being
--   transferred to or received from.
-- * @fileNumber@: The friend-specific identifier for the file transfer.
-- * @control@: The control command to send.
toxFileControl
    :: Tox
    -> FriendNumber
    -> FileNumber
    -> FileControl
    -> IO (Either ErrFileControl ())
toxFileControl (Tox tox) (FriendNumber friendNumber) (FileNumber fileNumber)
    control =
    callErrFun_ $
        Raw.tox_file_control tox friendNumber fileNumber (toCEnum control)

-- | Sends a file seek control command to a friend for a given file transfer.
--
-- This function can only be called to resume a file transfer right before
-- TOX_FILE_CONTROL_RESUME is sent.
--
-- * @friendNumber@: The friend number of the friend the file is being
--   received from.
-- * @fileNumber@: The friend-specific identifier for the file transfer.
-- * @position@: The position that the file should be seeked to.
toxFileSeek
    :: Tox -> FriendNumber -> FileNumber -> Word64 -> IO (Either ErrFileSeek ())
toxFileSeek (Tox tox) (FriendNumber friendNumber) (FileNumber fileNumber)
    position =
    callErrFun_ $ Raw.tox_file_seek tox friendNumber fileNumber position

-- | Copy the file id associated to the file transfer to a byte array.
--
-- * @friendNumber@: The friend number of the friend the file is being
--   transferred to or received from.
-- * @fileNumber@: The friend-specific identifier for the file transfer.
toxFileGetFileId
    :: Tox -> FriendNumber -> FileNumber -> IO (Either ErrFileGet FileId)
toxFileGetFileId (Tox tox) (FriendNumber friendNumber) (FileNumber fileNumber) =
    getFixedBytesErr $ Raw.tox_file_get_file_id tox friendNumber fileNumber

-- | Send a chunk of file data to a friend.
--
-- This function is called in response to the @file_chunk_request@ callback.
-- The length parameter should be equal to the one received though the
-- callback. If it is zero, the transfer is assumed complete. For files with
-- known size, Tox will know that the transfer is complete after the last byte
-- has been received, so it is not necessary (though not harmful) to send a
-- zero-length chunk to terminate. For streams, Tox will know that the
-- transfer is finished if a chunk with length less than the length requested
-- in the callback is sent.
--
-- * @friendNumber@: The friend number of the receiving friend for this file.
-- * @fileNumber@: The file transfer identifier returned by 'toxFileSend'.
-- * @position@: The file or stream position from which to continue reading.
toxFileSendChunk
    :: Tox
    -> FriendNumber
    -> FileNumber
    -> Word64
    -> ByteString
    -> IO (Either ErrFileSendChunk ())
toxFileSendChunk (Tox tox) (FriendNumber friendNumber) (FileNumber fileNumber)
    position data' =
    withBytesLen data' $ \dataPtr dataLen ->
        callErrFun_ $
            Raw.tox_file_send_chunk tox friendNumber fileNumber position dataPtr
                dataLen

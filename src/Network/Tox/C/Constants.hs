-- | The size of a Tox address in bytes.
--
-- Tox addresses are in the format @[Public Key (TOX_PUBLIC_KEY_SIZE
-- bytes)][nospam (4 bytes)][checksum (2 bytes)]@.
--
-- The checksum is computed over the Public Key and the nospam value. The
-- first byte is an XOR of all the even bytes (0, 2, 4, ...), the second byte
-- is an XOR of all the odd bytes (1, 3, 5, ...) of the Public Key and nospam.
toxAddressSize :: Int
toxAddressSize = 38

-- | The size of a Tox Conference unique id in bytes.
toxConferenceIdSize :: Int
toxConferenceIdSize = 32

-- | The size of a Tox DHT Public Key in bytes.
--
-- A DHT public key is never the same as the long term public key part of the
-- Tox address. It can be long-term (for DHT bootstrap nodes) or short term
-- ephemeral (for Tox client nodes).
toxDhtIdSize :: Int
toxDhtIdSize = 32

-- | The number of bytes in a file id.
toxFileIdLength :: Int
toxFileIdLength = 32

-- | Number of bytes in a group Chat ID.
toxGroupChatIdSize :: Int
toxGroupChatIdSize = 32

-- | Maximum length of a group custom lossless packet.
toxGroupMaxCustomLosslessPacketLength :: Int
toxGroupMaxCustomLosslessPacketLength = 1373

-- | Maximum length of a group custom lossy packet.
toxGroupMaxCustomLossyPacketLength :: Int
toxGroupMaxCustomLossyPacketLength = 1373

-- | Maximum length of a group name.
toxGroupMaxGroupNameLength :: Int
toxGroupMaxGroupNameLength = 48

-- | Maximum length of a group text message.
toxGroupMaxMessageLength :: Int
toxGroupMaxMessageLength = 1372

-- | Maximum length of a peer part message.
toxGroupMaxPartLength :: Int
toxGroupMaxPartLength = 128

-- | Maximum length of a group password.

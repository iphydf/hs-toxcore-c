--
-- Deprecated: The macro will be removed in 0.3.0. Use the function instead.
toxMaxStatusMessageLength :: Int
toxMaxStatusMessageLength = 1007

-- | The size of the nospam in bytes when written in a Tox address.
toxNospamSize :: Int
toxNospamSize = 4

-- | The amount of additional data required to store any encrypted byte array.
-- Encrypting an array of N bytes requires N + 'toxPassEncryptionExtraLength'
